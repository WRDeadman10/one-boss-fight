# -*- coding: utf-8 -*-
"""
Imports the custom FBX arena meshes generated by Blender into /Game/OneBossFight/Environment/Meshes.
Idempotent and safe to run headless.
"""

import os
import unreal

IMPORT_DIR = "c:/Users/winss/Documents/Unreal Projects/OneBossFight/Import/Environment"
DEST_PATH = "/Game/OneBossFight/Environment/Meshes"

def log(msg):
    unreal.log("[ImportArena] " + msg)

def main():
    unreal.EditorAssetLibrary.make_directory(DEST_PATH)
    
    if not os.path.isdir(IMPORT_DIR):
        log("Import directory not found: " + IMPORT_DIR)
        return
        
    fbx_files = [f for f in os.listdir(IMPORT_DIR) if f.lower().endswith(".fbx")]
    if not fbx_files:
        log("No FBX files found to import.")
        return
        
    log("Found %d FBX files to import: %s" % (len(fbx_files), str(fbx_files)))
    
    tasks = []
    for fbx_name in fbx_files:
        full_path = os.path.join(IMPORT_DIR, fbx_name).replace("\\", "/")
        asset_name = os.path.splitext(fbx_name)[0]
        
        task = unreal.AssetImportTask()
        task.set_editor_property('filename', full_path)
        task.set_editor_property('destination_path', DEST_PATH)
        task.set_editor_property('destination_name', asset_name)
        task.set_editor_property('replace_existing', True)
        task.set_editor_property('automated', True)
        task.set_editor_property('save', True)
        
        options = unreal.FbxImportUI()
        options.set_editor_property('import_mesh', True)
        options.set_editor_property('import_textures', False)
        options.set_editor_property('import_materials', True)
        options.set_editor_property('import_as_skeletal', False)
        
        mesh_data = options.static_mesh_import_data
        mesh_data.set_editor_property('auto_generate_collision', False)
        mesh_data.set_editor_property('one_convex_hull_per_ucx', True)
        mesh_data.set_editor_property('combine_meshes', True)
        
        task.set_editor_property('options', options)
        tasks.append(task)
        
    unreal.AssetToolsHelpers.get_asset_tools().import_asset_tasks(tasks)
    
    for task in tasks:
        imported_paths = task.get_editor_property('imported_object_paths')
        log("Imported: " + str(imported_paths))
        
    log("All arena meshes successfully imported!")

if __name__ == "__main__":
    main()
