"""Inventory source error/refusal tokens and show literal references in native tests.

This is a review aid: source/test string co-occurrence does not prove that a test
executes the production branch. The report therefore marks unverified semantic
coverage explicitly instead of treating a lexical match as a passing test.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

import sys as _sys
_sys.path.insert(0, str(Path(__file__).resolve().parent))  # BP-17: sibling atomic_io as a script or via -m
from atomic_io import atomic_create_text


LITERAL_RE = re.compile(r'TEXT\s*\(\s*"([^"\\]*(?:\\.[^"\\]*)*)"\s*\)')
TOKEN_RE = re.compile(r"^[A-Za-z][A-Za-z0-9_]*(?:\.[A-Za-z][A-Za-z0-9_]*)+")
CONTEXT_RE = re.compile(
    r"\b(?:Error|OutError|Errors|Refusal|Refused|Reject(?:ed)?|HardError|ContractViolation|Failure|Fail)\b",
    re.IGNORECASE,
)



_REPO = Path(__file__).resolve().parents[2]


def _display(path: Path) -> str:
    """BP-03: print repo-relative POSIX paths whether the inputs came from the (now absolute) defaults or a relative argument."""
    try:
        return path.resolve().relative_to(_REPO).as_posix()
    except ValueError:
        return path.as_posix()

def scan(source_root: Path, tests_root: Path):
    tests = [p for p in tests_root.rglob("*") if p.suffix in {".cpp", ".h"}]
    test_text = {p: p.read_text(encoding="utf-8-sig", errors="replace") for p in tests}
    records = {}
    for path in source_root.rglob("*"):
        if path.suffix not in {".cpp", ".h"} or tests_root in path.parents:
            continue
        for line_no, line in enumerate(path.read_text(encoding="utf-8-sig", errors="replace").splitlines(), 1):
            stripped = line.lstrip()
            if stripped.startswith(("//", "/*", "*")) or not CONTEXT_RE.search(line):
                continue
            for value in LITERAL_RE.findall(line):
                match = TOKEN_RE.match(value)
                if not match:
                    continue
                token = match.group(0)
                record = records.setdefault(token, {"sites": [], "tests": []})
                site = {"path": _display(path), "line": line_no}
                if site not in record["sites"]:
                    record["sites"].append(site)
    for token, record in records.items():
        record["sites"].sort(key=lambda row: (row["path"], row["line"]))
        record["tests"] = sorted(_display(p) for p, content in test_text.items() if token in content)
    return records


def render(records):
    lines = [
        "# U-C08 — Source HardError/refusal token audit (static inventory)",
        "",
        "Generated by `Scripts/Tools/audit_source_error_token_coverage.py` from production C++ string literals and native test source.",
        "A literal reference is only a candidate test link: it does not prove the test reaches the branch or observes the emitted token. `NO LITERAL TEST REFERENCE` is an explicit coverage gap to resolve; do not count it as passing.",
        "",
        f"Unique tokens inventoried: **{len(records)}**. Tokens with a literal reference in at least one native test: **{sum(bool(r['tests']) for r in records.values())}**. Tokens without a literal test reference: **{sum(not r['tests'] for r in records.values())}**.",
        "",
        "| Token | Production source sites | Native test source references | Coverage status |",
        "|---|---|---|---|",
    ]
    for token, record in sorted(records.items()):
        sites = "; ".join(f"`{s['path']}:{s['line']}`" for s in record["sites"])
        tests = "; ".join(f"`{p}`" for p in record["tests"]) or "—"
        status = "LITERAL REFERENCE ONLY — inspect execution/assertion" if record["tests"] else "NO LITERAL TEST REFERENCE — coverage unresolved"
        lines.append(f"| `{token}` | {sites} | {tests} | {status} |")
    lines.extend([
        "",
        "## Scope limits and next step",
        "",
        "The lexical census includes dotted identifiers in error/refusal context lines; it can include strings that are not public refusal reasons and can miss dynamically assembled tokens. A native test file that mentions a token may only use it as bad input. Review each row against its enclosing production branch and test body, then add or extend automation for every uncovered runtime path. This report is not a claim that U-C08 acceptance has passed.",
        "",
    ])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=Path(__file__).resolve().parents[2] / "Source" / "OneBossFight")  # BP-03: repo-root defaults
    parser.add_argument("--tests", type=Path, default=Path(__file__).resolve().parents[2] / "Source" / "OneBossFight" / "Tests")
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[2] / "Documentation" / "Boss" / "U_C08_ERROR_PATH_AUDIT.md")
    args = parser.parse_args()
    if args.output.exists():
        parser.error(f"refusing to overwrite existing report: {args.output}")
    records = scan(args.source, args.tests)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    atomic_create_text(args.output, render(records))  # BP-17: atomic, no-overwrite; same LF bytes as before
    print(f"tokens={len(records)} direct_test_refs={sum(bool(r['tests']) for r in records.values())} report={args.output}")


if __name__ == "__main__":
    main()
